import kiwiSheet from '../assets/characters/kiwi.png';
import sofiSheet from '../assets/characters/sofi.png';
import spritesJson from '../assets/characters/sprites.json';

/** States every character has */
export type BaseAnimationState = 'idle' | 'move' | 'jump';
/** States only characters with the duck skill have (Sofi) */
export type CrouchAnimationState = 'crouch' | 'crawl';
export type AnimationState = BaseAnimationState | CrouchAnimationState;
export type CharacterKey = 'kiwi' | 'sofi';

export interface Rect {
    x: number;
    y: number;
    width: number;
    height: number;
}

export interface FrameInfo {
    /** Raw art file the frame was built from (art/raw/...) */
    source: string;
    /** Drawn this many px above the bottom edge (a trot's airborne moment); 0 = feet on the bottom edge */
    lift: number;
    /** Opaque area of the frame (texture px) */
    bounds: Rect;
    /** Measured size of one drawn pixel in the raw art, for reference */
    sourceArtPixel: number;
}

export interface SpriteMeta {
    frameWidth: number;
    frameHeight: number;
    artPixel: number;
    states: BaseAnimationState[];
    optionalStates: CrouchAnimationState[];
    characters: Record<CharacterKey, CharacterSprites>;
}

export interface CharacterSprites {
    /** One entry per cell of the character's spritesheet */
    frames: FrameInfo[];
    /** Spritesheet frame indices each animation plays, in order (crouch/crawl only for characters that duck) */
    animations: Record<BaseAnimationState, number[]> & Partial<Record<CrouchAnimationState, number[]>>;
}

export interface Character {
    name: string;
    /** Spritesheet URL (resolved by Vite) */
    sheet: string;
    sprites: CharacterSprites;
    /** Physics body in texture px, relative to the frame's top-left */
    hitbox: Rect;
    /** Lower body while ducking (same width and feet line), or null if the character can't duck */
    crouchHitbox: Rect | null;
}

// sprites.json is generated by tools/build-sprites.mjs; JSON imports are typed loosely (states as
// string[]), so we narrow it here. tests/characters.test.ts checks the file really has this shape.
const sprites = spritesJson as SpriteMeta;

// Sheets come from `npm run build:sprites` (tools/build-sprites.mjs): every frame uses the same
// size per drawn pixel and has the feet on the frame's bottom edge. They're built at the size they're shown
// (scale 1), so Phaser's roundPixels can snap them to whole pixels; a scaled sprite at a fractional
// position gets resampled by the GPU and looks blurry while moving.
export const SPRITE_SCALE = 1;
export const FRAME_SIZE = { width: sprites.frameWidth, height: sprites.frameHeight } as const;

// Animation states every character provides. Animation keys are `${character}_${state}`.
export const ANIMATION_STATES: readonly BaseAnimationState[] = sprites.states;

// Frames per second. `move` and `crawl` are additionally sped up with the dog's speed in the scene.
export const ANIMATION_FRAME_RATE: Record<AnimationState, number> = { idle: 4, move: 8, jump: 8, crouch: 4, crawl: 6 };

// Physics body relative to the idle pose's opaque bounds (texture px): narrower than the art so ledges feel
// forgiving, bottom edge exactly on the feet. Fixed across animation frames.
// Heights are chosen to fit the 32px level grid with margin: standing ≈ 70px (needs 3 free tiles = 96px, never fits
// a 2-tile gap), ducked ≈ 50px (fits a 2-tile gap = 64px). See docs/level-design.md.
const HITBOX_WIDTH_RATIO = 0.7;
const HITBOX_HEIGHT_RATIO = 0.9;
const CROUCH_HEIGHT_RATIO = 0.83;

export function hitboxFor({ frames, animations }: CharacterSprites): Rect {
    const idleFrame = frames[animations.idle[0] ?? -1];
    if (!idleFrame) throw new Error('sprites.json: idle animation has no frames');
    const idle = idleFrame.bounds;
    const width = Math.round(idle.width * HITBOX_WIDTH_RATIO);
    const height = Math.round(idle.height * HITBOX_HEIGHT_RATIO);
    return {
        x: Math.round(idle.x + (idle.width - width) / 2),
        y: idle.y + idle.height - height,
        width,
        height,
    };
}

/** Same width and feet line as the standing hitbox, height from the crouch pose. */
export function crouchHitboxFor(characterSprites: CharacterSprites, standing: Rect): Rect | null {
    const index = characterSprites.animations.crouch?.[0];
    const crouchFrame = index === undefined ? undefined : characterSprites.frames[index];
    if (!crouchFrame) return null;
    const { y, height } = crouchFrame.bounds;
    const crouchHeight = Math.round(height * CROUCH_HEIGHT_RATIO);
    return { x: standing.x, width: standing.width, y: y + height - crouchHeight, height: crouchHeight };
}

function character(key: CharacterKey, name: string, sheet: string): Character {
    const characterSprites = sprites.characters[key];
    const hitbox = hitboxFor(characterSprites);
    return { name, sheet, sprites: characterSprites, hitbox, crouchHitbox: crouchHitboxFor(characterSprites, hitbox) };
}

export const CHARACTERS: Record<CharacterKey, Character> = {
    kiwi: character('kiwi', 'Kiwi', kiwiSheet),
    sofi: character('sofi', 'Sofi', sofiSheet),
};

export const CHARACTER_KEYS = Object.keys(CHARACTERS) as CharacterKey[];

/** Narrows untrusted strings (DOM select values, network messages) to a known character. */
export function isCharacterKey(value: unknown): value is CharacterKey {
    return typeof value === 'string' && Object.hasOwn(CHARACTERS, value);
}
